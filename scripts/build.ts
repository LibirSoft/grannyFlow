export function renderPrompts(): string {
  const p = {
    repo: '<repo>',
    branch: '<branch>',
    base: '<base>',
    context: 'Plan files - read them first: <plan files>\n<context: work-order files and override notes>',
    config: resolveConfig([]),
  }
  const plans = ['<plan files>']
  const stage = { number: 2, total: 2, name: '<stage name>', task: '<stage task>' }
  const classes = { verdict: 'confirmed', impact: 'major', likelihood: 'edge', fixCost: 'small', scope: 'in-scope', priority: 80, evidence: '<path:line + trigger steps>' } as const
  const decided = (id: string, action: 'fix' | 'residual', rule: number) => ({
    id,
    severity: '<severity>',
    file: '<file>',
    title: '<title>',
    detail: '<detail>',
    ...classes,
    decision: { rule, action, why: '<why>' },
  })
  const earlier: EarlierRound[] = [
    {
      round: 1,
      sent: [decided('<reviewer>-F<n>', 'fix', 6)],
      residual: [decided('<reviewer>-F<m>', 'residual', 8)],
      deviations: "<the fixer's deviations>",
      declined: [{ id: '<reviewer>-F<n>', reason: "<the fixer's reason>" }],
    },
  ]
  const stageLedger: EarlierRound[] = [{ ...earlier[0]!, loop: { id: 's<k>', name: 'Stage <k> (<stage name>)' } }]
  const overruled = [{ id: '<id>', repeatOf: 'r1/<reviewer>-F<n>', reason: "<the judge's reason>", said: "<the fixer's reason>" }]
  const setup = `cd '<repo>' && ${worktreeScript(p.config, '<branch>', '<base>', '<worktreeDir>/<branch-slug>')}`
  const job = detachedReview({ script: '', body: '<review script>' }, p.config, '.granny/review-<stage>-r<n>-<name>', '<repo>')
  const sections: Array<[string, string]> = [
    ['Granny - worktree setup, the helper agent on Claude Code (on Cursor, run the command yourself)', worktreeCommandPrompt('<repo>', '<branch>', setup)],
    ['Planner - a run with goal (context here is the run\'s context only; the plan files do not exist yet)', draftPrompt({ ...p, context: '<context: work-order files and override notes>' }, '<goal>', ['<repo>/.granny/plans/<branch-slug>.md'])],
    ['Plan reviewer - agent engine', agentPlanReviewPrompt(p, plans)],
    ['Plan reviewer - codex exec, the Codex plugin task and the {prompt} of a command engine', planReviewPrompt(p, plans)],
    ['Judge - plan review', planJudgePrompt(p, plans, []).replace(/\[\]$/, '<findings as JSON>')],
    ['Implementer - plan fix (round 1; later rounds extend the newest rN deltas section)', planFixPrompt(p, plans, 1, []).replace(/\[\]$/, '<accepted findings as JSON>')],
    ['Implementer - stage', implementPrompt(p, { task: '<stage task>' }, 1, 2, '<stage name>')],
    ['Implementer - fix', fixPrompt(p, '<stage name>', 1, []).replace(/\[\]$/, '<accepted findings as JSON>')],
    [
      'Implementer - fix, from round 2 on when the judge overruled the fixer (the plan fix gets the same OVERRULED block)',
      fixPrompt(p, '<stage name>', 2, [], overruled).replace(/\[\]$/, '<accepted findings as JSON>'),
    ],
    ['Granny - a check command, the helper agent on Claude Code (on opencode and omp granny runs it itself; a check with timeout runs as `timeout <s> bash -c \'<run>\'`, or `gtimeout` where only that is on PATH; for a check without a metric the parenthesis reads `if very long, the last 3000 characters are enough`)', checkCommandPrompt('<repo>', 'check <stage name> <check name>', "cd '<repo>' && <check run>", '<metric pattern>')],
    [
      'Implementer - repair (checks failed at `implement`, `fix r<n>` or `final`; one block per failed check)',
      repairPrompt(p, '<stage name>', 'implement', 1, [{ name: '<check name>', run: '<check run>', code: '<exit code>', note: '<metric note>', output: '<last 3000 characters of the output>' }], stage),
    ],
    [
      'Implementer - commit (`git status --porcelain` listed uncommitted changes before a check gate - label `commit <stage> <gate> #<n>`, a repair - or, with no checks or no commit at all, after the implementer, and with no checks after a fix - label `commit <stage> implement` or `commit <stage> fix r<n>`; the plan-file parts only when a plan file sits inside the repo, outside the work dir)',
      commitPrompt(p, '<stage name>', 'implement', ' M <file>\n?? <file>', ['<plan files inside the repo>'], stage),
    ],
    ['Implementer - merge (a stage that ran in its own worktree; its merge stopped on conflicts)', mergePrompt(p, '<stage name>', '<lane branch>', '<git merge output>')],
    ['Reviewer - agent engine', agentReviewPrompt(p, '<stage name>', '<stage start sha>', stage)],
    [
      'Granny - a review command, start: the helper agent on Claude Code for a Codex or command reviewer, in the diff review and the plan review (on opencode and omp granny runs the review script itself and waits for it)',
      reviewStartPrompt(p, '<stage name>', '<reviewer>', job.start),
    ],
    [
      `Granny - a review command, wait <k> (k = 1 to ${MAX_WAITS}; granny calls the next wait until one prints done)`,
      reviewWaitPrompt(p, '<stage name>', '<reviewer>', 1, MAX_WAITS, WAIT_SECONDS / 60, job.wait),
    ],
    ['Granny - a review command, read (after a wait printed done)', reviewReadPrompt(p, '<stage name>', '<reviewer>', job.read)],
    [`Granny - a review command, stop (after ${MAX_WAITS} waits without done)`, reviewStopPrompt(p, '<stage name>', '<reviewer>', job.stop)],
    ['Reviewer - command engine, the text {prompt} is filled with', commandReviewPrompt(p, '<stage name>', '<stage start sha>', stage)],
    ['Judge', judgePrompt(p, '<stage start sha>', [], [], stage).replace(/\[\]$/, '<findings as JSON>')],
    [
      'Judge - from round 2 on (the plan judge gets the same EARLIER DECISIONS block; one "Round N sent" entry per earlier fix round, followed by its "kept as residual" list when that round left residual findings, and P0/P1 findings join the list once a fixer declined findings; a field the finding does not have, such as the classes of an unjudged P0/P1, is left out; `(ratchet raised <what>)` follows the why when the ratchet raised the finding)',
      judgePrompt(p, '<stage start sha>', [], earlier, stage).replace(/\[\]$/, '<findings as JSON>'),
    ],
    [
      'Judge - retry note (appended once to the judge or plan judge prompt, label `judge <stage> r<n> retry`, when the judge left findings unclassified; when it returned nothing, the note is: `' +
        judgeRetryNote(null) +
        '`)',
      judgeRetryNote([{ id: '<id>', why: '<what was invalid, or: no classification in your answer>' }]),
    ],
    [
      "Judge - final review (from round 1 on, its EARLIER DECISIONS block starts with the decisions of every stage review in the repo, in stage order, one entry per stage review round under `s<k>/r<N>/<id>` labels - a stage's last round has no \"sent\" part when it sent nothing - followed by the final review's own earlier rounds as above)",
      judgePrompt(p, '<base>', [], stageLedger, undefined, WHOLE_BRANCH_NOTE).replace(/\[\]$/, '<findings as JSON>'),
    ],
    ['Final review - the note every reviewer prompt (after its first line naming the diff) and the judge prompt (after its first line) carry, with name `final review` and diff base `<base>`', WHOLE_BRANCH_NOTE],
    ['Extraction fallback', extractPrompt('<stage name>', '<raw review output>')],
    [
      'Claude Code - the line before every read-only prompt (an `agent` reviewer, the judge, the extraction agent, and the helpers that start, wait for, read and stop a review command)',
      readOnlyPrefix(false).trimEnd(),
    ],
    [
      'Claude Code - the lines before the prompt of an `agent` reviewer, the judge and the extraction agent with `readOnlyAgent` on (they run as the `granny-readonly` agent type)',
      readOnlyPrefix(true).trimEnd(),
    ],
    ['Granny - final check (the plan-file part only when a plan file sits inside the repo, outside the work dir)', finalPrompt(p, ['<plan files inside the repo>'])],
  ]
  return [
    '<!-- Generated by scripts/build.ts from src/core/prompts.ts and src/core/worktree.ts - do not edit by hand. -->',
    '# granny prompts',
    '',
    'The exact prompts the engines send, rendered with the default config. Fill the `<placeholders>`; replace the gates, language, attribution and rules lines when the user\'s config differs. For stage 1 drop the "Earlier stages are done" line. For a stage without a task, drop the TASK section and every sentence that names the TASK. A placeholder in single quotes is a shell argument: write each `\'` in its value as `\'\\\'\'`.',
    '',
    ...sections.map(([title, body]) => `## ${title}\n\n\`\`\`text\n${body}\n\`\`\`\n`),
  ].join('\n')
}

if (import.meta.main) {
  write(join(engines, 'claude-code/workflow.js'), await buildClaudeCode())
  write(join(engines, 'claude-code/hooks/granny-readonly-guard.mjs'), await buildReadOnlyGuard())
  write(join(engines, 'opencode/plugin/granny-workflow/index.js'), await buildOpencode())
  write(join(engines, 'opencode/plugin/granny-workflow/tui.js'), await buildOpencodeTui())
  write(join(engines, 'omp/extensions/granny-workflow/index.js'), await buildOmp())
  write(join(skill, 'references/prompts.md'), renderPrompts())
}
