import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { resolveConfig } from '../src/core/config'
import {
  agentPlanReviewPrompt,
  agentReviewPrompt,
  commandReviewPrompt,
  draftPrompt,
  extractPrompt,
  finalPrompt,
  fixPrompt,
  implementPrompt,
  judgePrompt,
  mergePrompt,
  planFixPrompt,
  planJudgePrompt,
  planReviewPrompt,
  worktreeCommandPrompt,
  type EarlierRound,
} from '../src/core/prompts'
import { worktreeScript } from '../src/core/worktree'

const root = join(import.meta.dir, '..')
const skill = join(root, 'skills/granny-workflow')
const engines = join(skill, 'engines')
const BANNER = '// Generated by scripts/build.ts from src/ - do not edit by hand.\n'

async function bundle(entry: string, target: 'browser' | 'bun'): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(root, entry)], target, format: 'esm', minify: false })
  if (!result.success) {
    for (const log of result.logs) console.error(log)
    throw new Error(`bundle failed: ${entry}`)
  }
  return result.outputs[0]!.text()
}

function write(path: string, text: string) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  console.log(`wrote ${path.slice(root.length + 1)} (${text.length} bytes)`)
}

export async function buildClaudeCode(): Promise<string> {
  const meta = readFileSync(join(root, 'src/adapters/claude-code/meta.js'), 'utf8').trim()
  const code = await bundle('src/adapters/claude-code/entry.ts', 'browser')
  const exportTail = /\nexport\s*\{\s*main\s*\};?\s*$/
  if (!exportTail.test(code)) throw new Error('claude-code bundle: expected a trailing `export { main }`')
  const body = code.replace(exportTail, '\n').replace(/^\/\/ .*\n/gm, '')
  for (const banned of ['Date.now(', 'Math.random(', 'new Date(', 'import ', 'require(']) {
    if (body.includes(banned)) throw new Error(`claude-code bundle contains ${banned} - Workflow scripts cannot use it`)
  }
  return `${meta}\n${BANNER}${body.trim()}\n\nreturn await main({ agent, log, phase, args })\n`
}

export async function buildOpencode(): Promise<string> {
  return BANNER + (await bundle('src/adapters/opencode/plugin.ts', 'bun'))
}

export function renderPrompts(): string {
  const p = {
    repo: '<repo>',
    branch: '<branch>',
    base: '<base>',
    context: 'Plan files - read them first: <plan files>\n<context: work-order files and override notes>',
    config: resolveConfig([]),
  }
  const plans = ['<plan files>']
  const earlier: EarlierRound[] = [
    { round: 1, sent: [{ id: '<reviewer>-F<n>', severity: '<severity>', file: '<file>', title: '<title>', detail: '<detail>' }], deviations: "<the fixer's deviations>" },
  ]
  const overruled = [{ id: '<id>', repeatOf: 'r1/<reviewer>-F<n>', round: 1, reason: "<the judge's reason>" }]
  const setup = `cd '<repo>' && ${worktreeScript(p.config, '<branch>', '<base>', '<worktreeDir>/<branch-slug>')}`
  const sections: Array<[string, string]> = [
    ['Granny - worktree setup, the helper agent on Claude Code (on Cursor, run the command yourself)', worktreeCommandPrompt('<repo>', '<branch>', setup)],
    ['Planner - a run with goal (context here is the run\'s context only; the plan files do not exist yet)', draftPrompt({ ...p, context: '<context: work-order files and override notes>' }, '<goal>', ['<repo>/.granny/plans/<branch-slug>.md'])],
    ['Plan reviewer - agent engine', agentPlanReviewPrompt(p, plans)],
    ['Plan reviewer - codex exec, the Codex plugin task and the {prompt} of a command engine', planReviewPrompt(p, plans)],
    ['Judge - plan review', planJudgePrompt(p, plans, []).replace(/\[\]$/, '<findings as JSON>')],
    ['Implementer - plan fix (round 1; later rounds extend the newest rN deltas section)', planFixPrompt(p, plans, 1, []).replace(/\[\]$/, '<accepted findings as JSON>')],
    ['Implementer - stage', implementPrompt(p, { task: '<stage task>' }, 1, 2, '<stage name>')],
    ['Implementer - fix', fixPrompt(p, '<stage name>', 1, []).replace(/\[\]$/, '<accepted findings as JSON>')],
    [
      'Implementer - fix, from round 2 on when the judge overruled the fixer (the plan fix gets the same OVERRULED block)',
      fixPrompt(p, '<stage name>', 2, [], overruled, earlier).replace(/\[\]$/, '<accepted findings as JSON>'),
    ],
    ['Implementer - merge (a stage that ran in its own worktree; its merge stopped on conflicts)', mergePrompt(p, '<stage name>', '<lane branch>', '<git merge output>')],
    ['Reviewer - agent engine', agentReviewPrompt(p, '<stage name>', '<stage start sha>')],
    ['Reviewer - command engine, the text {prompt} is filled with', commandReviewPrompt(p, '<stage name>', '<stage start sha>')],
    ['Judge', judgePrompt(p, '<stage start sha>', []).replace(/\[\]$/, '<findings as JSON>')],
    [
      'Judge - from round 2 on (the plan judge gets the same EARLIER ROUNDS block; one "Round N sent" entry per earlier fix round, and P0/P1 findings join the list once a fixer declined findings)',
      judgePrompt(p, '<stage start sha>', [], earlier).replace(/\[\]$/, '<findings as JSON>'),
    ],
    ['Extraction fallback', extractPrompt('<stage name>', '<raw review output>')],
    ['Granny - final check', finalPrompt(p)],
  ]
  return [
    '<!-- Generated by scripts/build.ts from src/core/prompts.ts and src/core/worktree.ts - do not edit by hand. -->',
    '# granny prompts',
    '',
    'The exact prompts the engines send, rendered with the default config. Fill the `<placeholders>`; replace the gates, language, attribution and rules lines when the user\'s config differs. For stage 1 drop the "Earlier stages are done" line. A placeholder in single quotes is a shell argument: write each `\'` in its value as `\'\\\'\'`.',
    '',
    ...sections.map(([title, body]) => `## ${title}\n\n\`\`\`text\n${body}\n\`\`\`\n`),
  ].join('\n')
}

if (import.meta.main) {
  write(join(engines, 'claude-code/workflow.js'), await buildClaudeCode())
  write(join(engines, 'opencode/plugin/granny-workflow/index.js'), await buildOpencode())
  write(join(skill, 'references/prompts.md'), renderPrompts())
}
